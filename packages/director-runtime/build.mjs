import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
const result = await build({
  entryPoints: [fileURLToPath(new URL("./src/player.ts", import.meta.url))],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "PocketDirector",
  target: "es2022",
  minify: true,
});
await writeFile(
  new URL("./src/bundle.generated.ts", import.meta.url),
  `// Generated by director-runtime/build.mjs\nexport const runtimeBundle = ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
